-- StudyQuest Daily Test: run this script in Supabase Dashboard > SQL Editor.
-- Demo leaderboard: public scores are not tamper-proof. For production, validate answers and award certificates server-side.
create table if not exists public.sq_daily_test_scores (
  id bigint generated by default as identity primary key,
  player_id text not null,
  player_name text not null check (char_length(player_name) between 1 and 40),
  week_start date not null,
  test_date date not null,
  score integer not null check (score >= 0),
  total integer not null check (total > 0 and score <= total),
  mode text not null default 'free' check (mode in ('free','premium')),
  created_at timestamptz not null default now()
);
create index if not exists sq_daily_test_scores_week_idx
  on public.sq_daily_test_scores (week_start, score desc, created_at asc);
alter table public.sq_daily_test_scores enable row level security;
drop policy if exists "Anyone can read weekly StudyQuest scores" on public.sq_daily_test_scores;
create policy "Anyone can read weekly StudyQuest scores"
  on public.sq_daily_test_scores for select to anon, authenticated using (true);
drop policy if exists "Anyone can submit a StudyQuest test score" on public.sq_daily_test_scores;
create policy "Anyone can submit a StudyQuest test score"
  on public.sq_daily_test_scores for insert to anon, authenticated
  with check (
    char_length(player_name) between 1 and 40
    and score >= 0 and total > 0 and score <= total
    and mode in ('free','premium')
  );
grant select, insert on public.sq_daily_test_scores to anon, authenticated;
grant usage, select on sequence public.sq_daily_test_scores_id_seq to anon, authenticated;
